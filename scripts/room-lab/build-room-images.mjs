// Writes the responsive copies of the /room-lab photo and its furniture cutout into public/room-lab/ (committed, served as static files):
//   room-<w>.webp     the bare room, 800 / 1200 / 1600 / 2000 px wide
//   cutout-<w>.webp   the same picture with only the furniture left (alpha), made by scripts/room-lab/make-cutout.py
//   room-tiny.webp    a 40 px blurred copy, inlined as the first paint while the full photo loads
// Run: node scripts/room-lab/build-room-images.mjs     (sources: assets/room-lab/room-bare.webp and room-cutout.png)
import sharp from 'sharp';
import { mkdirSync, writeFileSync } from 'node:fs';

const WIDTHS = [800, 1200, 1600, 2000];
mkdirSync('public/room-lab', { recursive: true });
for (const w of WIDTHS) {
  await sharp('assets/room-lab/room-bare.webp').resize({ width: w }).webp({ quality: 86, effort: 6 }).toFile(`public/room-lab/room-${w}.webp`);
  await sharp('assets/room-lab/room-cutout.png').resize({ width: w }).webp({ quality: 86, alphaQuality: 100, effort: 6 }).toFile(`public/room-lab/cutout-${w}.webp`);
}
const tiny = await sharp('assets/room-lab/room-bare.webp').resize({ width: 40 }).webp({ quality: 60 }).toBuffer();
writeFileSync('src/room/roomTiny.js', `// generated by scripts/room-lab/build-room-images.mjs\nexport default 'data:image/webp;base64,${tiny.toString('base64')}';\n`);
console.log('room images written');
